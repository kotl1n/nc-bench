def build_rag_ru():
    data = []
    for meta in ITEMS_META:
        item_id = meta["id"]
        task = meta["task"]
        ctx_id = meta["ctx_id"]
        ctx_ru = CONTEXTS_RU[ctx_id]
        
        turns_ru = TURNS_RU[item_id]
        
        chat_prompt = [{"role": "system", "content": SYS_PREFIX_RU + ctx_ru}]
        for role, content in turns_ru:
            chat_prompt.append({"role": role, "content": content})
            
        entry = {
            "id": item_id,
            "original_id": item_id,
            "ru_id": f"rag_{item_id:03d}",
            "task": task,
            "chat_prompt": chat_prompt
        }
        data.append(entry)
        
    data.sort(key=lambda x: x["id"])
    return data

