def build_rag_ru():
    data = []
    for meta in ITEMS_META:
        item_id = meta["id"]
        task = meta["task"]
        ctx_id = meta["ctx_id"]
        ctx_ru = CONTEXTS_RU[ctx_id]
        
        turns_ru = TURNS_RU[item_id]
        
        chat_prompt = [{"role": "system", "content": SYS_PREFIX_RU + ctx_ru}]
        for role, content in turns_ru:
            chat_prompt.append({"role": role, "content": content})
            
        entry = {
            "id": item_id,
            "original_id": item_id,
            "ru_id": f"rag_{item_id:03d}",
            "task": task,
            "chat_prompt": chat_prompt
        }
        data.append(entry)
        
    data.sort(key=lambda x: x["id"])
    return data

if __name__ == "__main__":
    ru_data = build_rag_ru()
    assert len(ru_data) == 180, f"Expected 180, got {len(ru_data)}"
    out_path = "nc-bench/data_ru/conversation_competence_rag_ru.jsonl"
    with open(out_path, "w", encoding="utf-8") as f:
        for row in ru_data:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Successfully generated {len(ru_data)} RAG items in {out_path}")
